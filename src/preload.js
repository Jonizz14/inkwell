const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  list: () => ipcRenderer.invoke('library:list'),
  article: (id) => ipcRenderer.invoke('library:article', id),
  openPdf: (id) => ipcRenderer.invoke('library:openPdf', id),
  pick: () => ipcRenderer.invoke('library:pick'),
  importFiles: (files) => ipcRenderer.invoke('library:importPaths', [...files].map((f) => webUtils.getPathForFile(f))),
  scanInbox: () => ipcRenderer.invoke('library:scanInbox'),
  inboxPath: () => ipcRenderer.invoke('library:inboxPath'),
  openInbox: () => ipcRenderer.invoke('library:openInbox'),
  loadNotes: () => ipcRenderer.invoke('notes:load'),
  saveNotes: (data) => ipcRenderer.invoke('notes:save', data),
  copy: (text) => ipcRenderer.invoke('clipboard:write', text),
  vocabPdf: (html, name) => ipcRenderer.invoke('vocab:pdf', { html, name }),
  readClipboard: () => ipcRenderer.invoke('clipboard:read'),
  onImportProgress: (fn) => ipcRenderer.on('import:progress', (_e, p) => fn(p)),
  readStart: (opts) => ipcRenderer.invoke('read:start', opts),
  readStop: () => ipcRenderer.invoke('read:stop'),
  onRead: (fn) => void ipcRenderer.on('read:event', (_e, m) => fn(m)),
  remindTarget: () => ipcRenderer.invoke('remind:target'),
  remindSync: (notes) => ipcRenderer.invoke('remind:sync', notes),
  remindTest: () => ipcRenderer.invoke('remind:test'),
  remindSettings: () => ipcRenderer.invoke('remind:settings'),
  onRemindOpen: (fn) => void ipcRenderer.on('remind:open', (_e, t) => fn(t)),
  // updates (update.js ↔ update-ui.js)
  onUpdateAvailable: (fn) => void ipcRenderer.on('update:available', (_e, i) => fn(i)),
  onUpdateProgress: (fn) => void ipcRenderer.on('update:progress', (_e, p) => fn(p)),
  onUpdateStaged: (fn) => void ipcRenderer.on('update:staged', (_e, v) => fn(v)),
  onUpdateFailed: (fn) => void ipcRenderer.on('update:failed', (_e, m) => fn(m)),
  onUpdateHold: (fn) => void ipcRenderer.on('update:hold', () => fn()),
  updateRun: () => ipcRenderer.invoke('update:run'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  storageUsage: () => ipcRenderer.invoke('storage:usage'),
  storageClear: (part) => ipcRenderer.invoke('storage:clear', part),
  storageShow: (part) => ipcRenderer.invoke('storage:show', part),
  updateDone: () => ipcRenderer.invoke('update:done'),
  updateDemo: () => ipcRenderer.invoke('update:demo'),
  updateRestart: (v) => ipcRenderer.invoke('update:restart', v),
  updateBusy: (on) => ipcRenderer.send('update:busy', on),
  listenFeed: (kind, id) => ipcRenderer.invoke('listen:feed', kind, id),
  listenResolve: (url) => ipcRenderer.invoke('listen:resolve', url),
  // The Guardian shelf (guardian.js): 'test' | 'feed' | 'add'
  guardian: (what, ...a) => (['test', 'feed', 'add'].includes(what) ? ipcRenderer.invoke('guardian:' + what, ...a) : Promise.reject(new Error('no such call'))),
  addons: () => ipcRenderer.invoke('addons:list'),
  // add-ons call their own channels (src/private/<name>-main.js)
  invoke: (ch, ...a) => (/^addon:/.test(ch) ? ipcRenderer.invoke(ch, ...a) : Promise.reject(new Error('not an add-on channel'))),
  widgetNow: (notes) => ipcRenderer.invoke('widget:now', notes),
  fullscreen: (on) => ipcRenderer.invoke('win:fullscreen', on),
  libDir: () => ipcRenderer.invoke('library:dir'),
  onLibraryChanged: (fn) => void ipcRenderer.on('library:changed', () => fn()),
  haptic: (k) => ipcRenderer.send('haptic', k),
  platform: process.platform,
});
